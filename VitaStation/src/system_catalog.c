size_t system_feature_count(void){return sizeof(features)/sizeof(features[0]);}
const SystemFeature *system_feature_get(size_t index){return index<system_feature_count()?&features[index]:NULL;}

const char*system_feature_reason(const SystemFeature*f){
 if(!f)return "Opcao desconhecida.";
 if(f->control>=200)return "Abre a funcao correspondente dentro do VitaStation.";
 if(f->control>=100)return "Consulta real; esta pagina nao altera a definicao do sistema.";
 if(f->control>=0)return "Controlo nativo implementado; a consola confirma o resultado.";
 if(!strcmp(f->category,"Conta e PSN"))return "Requer servico PSN autenticado e adaptador de conta validado.";
 if(!strcmp(f->category,"Troféus"))return "Requer contextos e base de trofeus do sistema; adaptador ainda indisponivel.";
 if(!strcmp(f->category,"Rede"))return "Edicao/scan de rede ainda sem adaptador do sistema validado.";
 if(!strcmp(f->category,"Dispositivos"))return "Requer servico de dispositivos e emparelhamento ainda nao implementado.";
 if(!strcmp(f->category,"Segurança e armazenamento"))return "Requer adaptador dedicado; nao executa alteracoes de seguranca ou restauro incompletas.";
 return "Funcao auditada: nao existe adaptador validado nesta versao.";
}
